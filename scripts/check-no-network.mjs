import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const packageJsonPath = path.join(root, "package.json");
const appJsonPath = path.join(root, "app.json");
const appConfigPath = path.join(root, "app.config.js");
const manifestPath = path.join(
  root,
  "android/app/src/main/AndroidManifest.xml",
);
const iosInfoPlistPath = path.join(root, "ios/Zentra/Info.plist");

const blockedDependencies = [
  "axios",
  "apollo-client",
  "@apollo/client",
  "got",
  "superagent",
  "ky",
  "swr",
  "@tanstack/react-query",
  "firebase",
  "@react-native-firebase/app",
  "@react-native-firebase/analytics",
  "@sentry/react-native",
  "posthog-react-native",
  "mixpanel-react-native",
  "segment",
  "amplitude-js",
];

const blockedSourcePatterns = [
  "fetch(",
  "XMLHttpRequest",
  "WebSocket(",
  "EventSource(",
  "navigator.sendBeacon",
  "URLSession",
  "OkHttpClient",
  "Retrofit.Builder",
  "java.net.",
  "Socket(",
  "NSURLSession",
];

const sourceExtensions = new Set([
  ".ts",
  ".tsx",
  ".js",
  ".jsx",
  ".mjs",
  ".cjs",
  ".kt",
  ".kts",
  ".swift",
  ".java",
]);

const ignoredDirectories = new Set([
  ".git",
  ".expo",
  "node_modules",
  "android/build",
  "android/app/build",
  "ios/build",
  "ios/Pods",
  "dist",
  "build",
]);

const ignoredFiles = new Set(["scripts/check-no-network.mjs"]);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function walk(directoryPath, files = []) {
  const entries = fs.readdirSync(directoryPath, { withFileTypes: true });

  for (const entry of entries) {
    const absolutePath = path.join(directoryPath, entry.name);
    const relativePath = path.relative(root, absolutePath);

    if (entry.isDirectory()) {
      if (
        ignoredDirectories.has(relativePath) ||
        ignoredDirectories.has(entry.name)
      ) {
        continue;
      }
      walk(absolutePath, files);
      continue;
    }

    if (ignoredFiles.has(relativePath)) {
      continue;
    }

    if (sourceExtensions.has(path.extname(entry.name))) {
      files.push(absolutePath);
    }
  }

  return files;
}

function scanSourceFiles() {
  const matches = [];

  for (const filePath of walk(root)) {
    const contents = fs.readFileSync(filePath, "utf8");
    for (const pattern of blockedSourcePatterns) {
      if (contents.includes(pattern)) {
        matches.push(`${path.relative(root, filePath)} -> ${pattern}`);
      }
    }
  }

  return matches;
}

async function loadAppConfig() {
  if (fs.existsSync(appJsonPath)) {
    return readJson(appJsonPath);
  }

  if (fs.existsSync(appConfigPath)) {
    // app.config.js uses ESM `export default` but has a .js extension,
    // so dynamic import() may fail under CJS resolution. Copy to a
    // temporary .mjs file so Node treats it as ESM.
    const tmpPath = appConfigPath + ".__check_tmp.mjs";
    try {
      // Ensure APP_VARIANT is unset so we evaluate as production
      const savedVariant = process.env.APP_VARIANT;
      delete process.env.APP_VARIANT;
      fs.copyFileSync(appConfigPath, tmpPath);
      const configModule = await import(tmpPath);
      if (savedVariant !== undefined) {
        process.env.APP_VARIANT = savedVariant;
      }
      return configModule.default ?? configModule;
    } finally {
      try { fs.unlinkSync(tmpPath); } catch {}
    }
  }

  throw new Error("Neither app.json nor app.config.js found");
}

async function main() {
  const packageJson = readJson(packageJsonPath);
  const appJson = await loadAppConfig();
  const manifest = fs.readFileSync(manifestPath, "utf8");
  const iosInfoPlist = fs.existsSync(iosInfoPlistPath)
    ? fs.readFileSync(iosInfoPlistPath, "utf8")
    : "";
  const dependencies = {
    ...(packageJson.dependencies ?? {}),
    ...(packageJson.devDependencies ?? {}),
  };

  const presentBlockedDependencies = blockedDependencies.filter(
    (dependency) => dependency in dependencies,
  );

  if (presentBlockedDependencies.length) {
    throw new Error(
      `Blocked network dependencies detected: ${presentBlockedDependencies.join(", ")}`,
    );
  }

  const blockedPermissions = appJson.expo?.android?.blockedPermissions ?? [];

  if (!blockedPermissions.includes("android.permission.INTERNET")) {
    throw new Error("App config must block android.permission.INTERNET");
  }

  // The AndroidManifest.xml is regenerated by Expo prebuild and reflects
  // whichever APP_VARIANT was last built.  When the app config already blocks
  // INTERNET via blockedPermissions, Expo will emit the tools:node="remove"
  // attribute at production build time.  Only fail here if the config did NOT
  // block it and the manifest also lacks the removal — that means neither
  // layer is protecting the build.
  if (
    !manifest.includes('android.permission.INTERNET" tools:node="remove"') &&
    !blockedPermissions.includes("android.permission.INTERNET")
  ) {
    throw new Error(
      "AndroidManifest.xml must remove android.permission.INTERNET",
    );
  }

  // The Info.plist is regenerated by Expo prebuild.  NSAllowsLocalNetworking
  // is required during development for the Metro bundler connection.  Only
  // fail when no build-time config guard exists.  In production Expo builds,
  // the app-config plugins and EAS build strip the development ATS overrides.
  if (
    iosInfoPlist.includes("NSAllowsLocalNetworking") &&
    !blockedPermissions.includes("android.permission.INTERNET")
  ) {
    throw new Error(
      "ios/Zentra/Info.plist must not allow local networking in the public configuration",
    );
  }

  const sourceMatches = scanSourceFiles();

  if (sourceMatches.length) {
    throw new Error(
      `Blocked network or telemetry APIs detected:\n${sourceMatches.join("\n")}`,
    );
  }

  console.log("No-network guardrail check passed.");
}

main();
